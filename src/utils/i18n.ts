export function t(key: keyof typeof translations['bn'], lang: Language): string {
  return translations[lang]?.[key] || translations['bn'][key] || key;
}

export function formatNumber(num: number | string, lang: Language): string {
  if (num === undefined || num === null || isNaN(Number(num))) return '0';
  const n = Number(num).toLocaleString('en-IN');
  if (lang === 'en') return n;
  
  // Bengali numerals conversion
  const bengaliDigits = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];
  return n.replace(/[0-9]/g, (w) => bengaliDigits[+w]);
}

export function getMonthName(monthNumber: number, lang: Language): string {
  const bnMonths = [
    'জানুয়ারি', 'ফেব্রুয়ারি', 'মার্চ', 'এপ্রিল', 'মে', 'জুন',
    'জুলাই', 'আগস্ট', 'সেপ্টেম্বর', 'অক্টোবর', 'নভেম্বর', 'ডিসেম্বর'
  ];
  const enMonths = [
    'January', 'February', 'March', 'April', 'May', 'June',
    'July', 'August', 'September', 'October', 'November', 'December'
  ];
  return lang === 'bn' ? bnMonths[monthNumber - 1] || '' : enMonths[monthNumber - 1] || '';
}
